// ---
// relationships:
//   implements: blueprint-authoring
// ---
import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { parse } from "yaml";
import { format } from "prettier";

const contracts = JSON.parse(
  await readFile("src/blueprints/node-types.json", "utf8"),
);
const outputRoot = process.argv[2] ?? ".";
const hookFiles = JSON.parse(
  await readFile("src/agent-tools/plugin-contracts.json", "utf8"),
);
const schema = parse(
  await readFile("docs/specifications/blueprint.schema.yml", "utf8"),
);
const rulesSource = await readFile("src/blueprints/rules.ts", "utf8");
const rules = [
  ...rulesSource.matchAll(
    /name: "([^"]+)"[\s\S]*?description:\s*(?:"([^"]+)"|\n\s*"([^"]+)")/g,
  ),
].map((match) => ({ name: match[1], description: match[2] ?? match[3] }));

const shipped = (await readdir("blueprints", { recursive: true }))
  .filter((path) => path.endsWith(".yml") && !path.startsWith("rules/"))
  .sort();

const definitionName = (contract) =>
  contract.paramsSchema.$ref.split("/").at(-1);
const fenced = (value) =>
  `\n\`\`\`yaml\n${JSON.stringify(value, null, 2)}\n\`\`\`\n`;
let reference = `---\nrelationships:\n  implements:\n    - blueprint-authoring\n    - node-types\n---\n\n# Blueprint author reference\n\nThis file is generated from the node-type registry, blueprint schema, validation-rule registry, shipped blueprints, and hook-plugin file registry. Run \`task build\` to regenerate it.\n\n## Engine agreement\n\nHeddle dispatches Flowcraft nodes sequentially with engine concurrency 1. Durable snapshot checkpointing and the one-terminal-result guard depend on that order. A concurrency change must replace those agreements before it changes dispatch.\n\nEvery completed node writes its output below its authored node id. A pausing result is also exposed during edge routing as \`result.output.<result>\`; its wake payload is \`result.output.payload\`.\n\n## Node types\n`;
for (const [name, contract] of Object.entries(contracts)) {
  const params = schema.$defs[definitionName(contract)];
  reference += `\n### \`${name}\`\n\n${contract.description}\n\n- Pausing: ${contract.pausing ? "yes" : "no"}\n- Results: ${contract.results.length ? contract.results.map((x) => `\`${x}\``).join(", ") : "none"}\n- Context keys written: ${contract.contextWrites.map((x) => `\`${x}\``).join(", ")}\n- Inputs and defaults:${fenced(params)}- Output:${fenced(contract.outputSchema)}`;
}
reference += `\n## Validation rules\n\n${rules.map((rule) => `- \`${rule.name}\`: ${rule.description}`).join("\n")}\n\n## Shipped blueprints\n\n${shipped.map((path) => `- \`blueprints/${path}\``).join("\n")}\n\n## Harness hook files\n\n${Object.entries(
  hookFiles,
)
  .map(
    ([harness, files]) =>
      `### ${harness}\n\n${files.map((path) => `- \`${path}\``).join("\n")}`,
  )
  .join("\n\n")}\n`;

const skill = `---\nname: blueprint-authoring\ndescription: Author and repair Heddle blueprint repositories from the embedded node contracts. Use when creating or editing Heddle blueprint YAML, referenced templates, handoff schemas, policy rules, or child-run compositions.\nmetadata:\n  relationships:\n    implements: blueprint-authoring\n---\n\n# Author Heddle blueprints\n\nRead \`references/blueprint-author-reference.md\` before editing. It is generated from the same contracts that Heddle validates.\n\nUse generic names and scenarios. Keep every referenced template, schema, and rule file beside its blueprint. Use condition edges for routing and route every named result of each pausing node. Do not use action edges or Flowcraft subflows.\n\nAfter every blueprint or referenced-file edit, run:\n\n\`\`\`sh\nheddle validate --json <file-or-repository>\n\`\`\`\n\nRead every finding, fix it, and rerun the same command. Continue until the JSON output is \`[]\`. Do not treat readable YAML, schema validation alone, or an earlier clean run as validation of the latest edit.\n\nHeddle dispatches nodes sequentially. Do not author or document a workflow that depends on concurrent node execution.\n`;

const generatedModule = `// Generated by scripts/generate-authoring.mjs.\nexport const BLUEPRINT_AUTHORING_SKILL = ${JSON.stringify(skill)};\nexport const BLUEPRINT_AUTHOR_REFERENCE = ${JSON.stringify(reference)};\n`;
for (const [path, content] of [
  ["docs/reference/blueprint-author-reference.md", reference],
  ["skills/blueprint-authoring/SKILL.md", skill],
  [
    "skills/blueprint-authoring/references/blueprint-author-reference.md",
    reference,
  ],
  ["src/generated/blueprint-authoring.ts", generatedModule],
]) {
  const output = join(outputRoot, path);
  await mkdir(dirname(output), { recursive: true });
  await writeFile(
    output,
    await format(content, {
      filepath: path,
      proseWrap: "preserve",
    }),
  );
}
